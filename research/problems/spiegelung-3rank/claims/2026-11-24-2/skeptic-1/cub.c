// Independent recomputation: count GL2(Z)-classes of integral binary cubic forms per discriminant.
// For a fundamental discriminant D, #classes(D) = 1 + (3^r3(D) - 1)/2  (1 reducible class Z+O_K, plus cubic fields).
// Real forms (disc>0): reduce via Hessian (P,Q,R), 0<=Q<=P<=R. Complex (disc<0): reduce via the complex root beta
// of the form, beta in the GL2(Z) fundamental domain. Boundary cases resolved by explicit orbit canonicalisation.
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <math.h>
typedef int64_t i64; typedef __int128 i128;
static inline i64 fdiv(i64 a,i64 b){ i64 q=a/b; if((a%b!=0)&&((a<0)!=(b<0))) q--; return q; }
static inline i64 cdiv(i64 a,i64 b){ return -fdiv(-a,b); }

static uint8_t *RA,*C3,*CN; static i64 Lseg,Hseg,baseR,NL,NH,baseN;
static unsigned long long ntrip=0,ntrip2=0,nform_real=0,nform_c3=0,nform_cn=0,nslow=0;

typedef struct {i64 v[4];} F4;
static int lexcmp(const F4*x,const F4*y){ for(int i=0;i<4;i++){ if(x->v[i]<y->v[i])return -1; if(x->v[i]>y->v[i])return 1;} return 0; }
static F4 app(F4 f,int g){ i64 a=f.v[0],b=f.v[1],c=f.v[2],d=f.v[3]; F4 r;
  switch(g){
    case 0: r=(F4){{-a,-b,-c,-d}}; break;            // -I
    case 1: r=(F4){{a,-b,c,-d}}; break;              // (x,-y)
    case 2: r=(F4){{d,c,b,a}}; break;                // swap
    case 3: r=(F4){{a,-3*a-b,3*a+2*b+c,-a-b-c-d}}; break; // (x-y,-y)
    default: r=(F4){{a,3*a-b,3*a-2*b+c,a-b+c-d}}; break;  // (x+y,-y)
  } return r; }
// is f the lexicographic maximum of its orbit under the group generated by gens (bitmask) and -I ?
static int is_canon(F4 f,int gens){
  F4 orb[64]; int n=1; orb[0]=f; gens|=1;
  for(int i=0;i<n;i++) for(int g=0;g<5;g++) if(gens>>g&1){
    F4 h=app(orb[i],g); int found=0; for(int j=0;j<n;j++) if(lexcmp(&h,&orb[j])==0){found=1;break;}
    if(!found){ if(n>=64){fprintf(stderr,"orbit overflow\n");exit(3);} orb[n++]=h; if(lexcmp(&h,&f)>0) return 0; } }
  return 1; }

static inline void bump(uint8_t*p){ if(*p<255)(*p)++; }

// mode 0: real, key=disc in [Lseg,Hseg); mode 1: complex, |disc|=3m, m in [Lseg,Hseg); mode 2: complex |disc|=n in [NL,NH)
static inline void record(int mode,i64 k){
  if(mode==0){ i64 d=-k; nform_real++; bump(&RA[2*(d>>2)+(d&1)-baseR]); }
  else if(mode==1){ i64 m=k/3; nform_c3++; if((m&3)<2) bump(&C3[2*(m>>2)+(m&1)-baseR]); }
  else { nform_cn++; int r=k&3; if(r==0||r==3) bump(&CN[2*(k>>2)+(r==3)-baseN]); }
}

// handle fixed (a,b,c), a>=0; d in [d1,d2]; valid iff Ti < k(d) <= To
static void do_triple(int mode,i64 a,i64 b,i64 c,i64 d1,i64 d2,i64 Ti,i64 To){
  if(d1>d2) return;
  i64 A=27*a*a, B=-(18*a*b*c-4*b*b*b), C=4*a*c*c*c-b*b*c*c;
  i64 lo[2],hi[2]; int ni=0; ntrip++;
  if(a>0){ // quick rejection using convexity of k(d)
    i64 k1=(A*d1+B)*d1+C, k2=(A*d2+B)*d2+C;
    if(k1<=Ti&&k2<=Ti) return;
    i64 dv=fdiv(-B,2*A); 
    if(dv<d1){ if(k1>To) return; } else if(dv>=d2){ if(k2>To) return; }
    else { i64 ka=(A*dv+B)*dv+C, kb=(A*(dv+1)+B)*(dv+1)+C; if(ka>To&&kb>To) return; }
  }
  ntrip2++;
  if(a==0){ /* k = B d + C, B=4b^3>0 */ i64 l=fdiv(Ti-C,B)+1, h=fdiv(To-C,B); if(l<d1)l=d1; if(h>d2)h=d2; if(l>h) return; lo[0]=l;hi[0]=h;ni=1; }
  else {
    i128 Do=(i128)B*B-(i128)4*A*((i128)C-To);
    if(Do<0) return;
    double s=sqrt((double)Do), tA=2.0*A;
    i64 l=(i64)floor((-(double)B-s)/tA)-2, h=(i64)ceil((-(double)B+s)/tA)+2;
    if(l<d1)l=d1; if(h>d2)h=d2; if(l>h) return;
    i128 Di=(i128)B*B-(i128)4*A*((i128)C-Ti);
    if(Di>0){ double si=sqrt((double)Di);
      i64 e1=(i64)ceil((-(double)B-si)/tA)+2, e2=(i64)floor((-(double)B+si)/tA)-2;
      if(e1<=e2){ // excluded [e1,e2]
        if(l<=e1-1){ lo[ni]=l; hi[ni]=(e1-1<h?e1-1:h); ni++; }
        if(e2+1<=h){ i64 st=(e2+1>l?e2+1:l); if(ni==1&&st<=hi[0]) st=hi[0]+1; if(st<=h){lo[ni]=st;hi[ni]=h;ni++;} }
      } else { lo[0]=l;hi[0]=h;ni=1; }
    } else { lo[0]=l;hi[0]=h;ni=1; }
  }
  i64 step=1, res=0;
  if(mode==1){ // need disc = 0 mod 3 : disc = b^2c^2 - a c^3 - b^3 d (mod 3)
    i64 bm=((b%3)+3)%3, am=a%3, cm=((c%3)+3)%3;
    if(bm==0){ if((am*cm)%3!=0) return; }
    else { step=3; res=(((cm*cm - am*cm*cm*cm)%3+3)%3*bm)%3; }
  }
  i64 P=0; if(mode==0) P=b*b-3*a*c;
  for(int t=0;t<ni;t++){
    i64 d=lo[t];
    if(step==3){ i64 dm=((d%3)+3)%3; d+=((res-dm)%3+3)%3; }
    for(;d<=hi[t];d+=step){
      i64 k=(A*d+B)*d+C;
      if(k<=Ti||k>To) continue;
      int gens=0;
      if(mode==0){
        i64 Q=b*c-9*a*d, R=c*c-3*b*d;
        if(Q<0||Q>P||R<P) continue;
        if(Q==0)gens|=2; if(Q==P)gens|=16; if(P==R)gens|=4;
      } else {
        i64 u1=a*d-b*c, u2=(a+b)*(a+b)+a*c;
        if(a>0){
          if(u1<0||u1>u2) continue;
          i64 v1=d*d-a*a, v2=b*d-a*c; if(v1<v2) continue;
          if(u1==0)gens|=2; if(u1==u2)gens|=8; if(v1==v2)gens|=4;
        } else { // y*(b x^2 + c xy + d y^2), b>0, -b<=c<=0, d>=b
          if(c>0||c<-b||d<b) continue;
          if(c==0)gens|=2; if(c==-b)gens|=8; if(d==b)gens|=4;
        }
      }
      if(gens && !(a==0 && !(gens&4))){ nslow++; F4 f={{a,b,c,d}}; if(!is_canon(f,gens)) continue; }
      record(mode,k);
    }
  }
}

static void enum_real(i64 L,i64 H){ // L<=disc<H
  long double X=(long double)H; i64 sq=(i64)sqrtl(X)+1; long double q4=sqrtl(sqrtl(X));
  i64 Ti=-H, To=-L; if(To>-1)To=-1;
  // a=0: (0,b,c,d), b>0, 0<=c<=b, R=c^2-3bd>=b^2, disc=b^2(c^2-4bd)
  for(i64 b=1;b<=(i64)q4+1;b++) for(i64 c=0;c<=b;c++){
    i64 d2=fdiv(c*c-b*b,3*b), d1=-(H/(4*b*b*b))-2; do_triple(0,0,b,c,d1,d2,Ti,To); }
  i64 amax=(i64)sqrtl(4.0L*sqrtl(X)/27.0L)+1;
  for(i64 a=1;a<=amax;a++){
    i64 bm=(i64)(1.5L*a+q4)+2;
    for(i64 b=-bm;b<=bm;b++){
      i64 c1=cdiv(b*b-sq,3*a)-1, c2=fdiv(b*b-1,3*a);
      for(i64 c=c1;c<=c2;c++){
        i64 P=b*b-3*a*c; if(P<1) continue;
        do_triple(0,a,b,c,cdiv(b*c-P,9*a),fdiv(b*c,9*a),Ti,To);
      }
    }
  }
}
static void enum_cplx(int mode,i64 Tlo,i64 Thi){ // Tlo<=|disc|<Thi
  if(Tlo<1)Tlo=1; if(Thi<=Tlo) return;
  long double X=(long double)Thi; i64 Ti=Tlo-1, To=Thi-1;
  long double q4=sqrtl(sqrtl(X));
  // a=0: y(bx^2+cxy+dy^2): |disc| = b^2(4bd-c^2)
  for(i64 b=1;b<=(i64)q4+1;b++) for(i64 c=-b;c<=0;c++){
    i64 d1=b, d2=(Thi/(b*b)+c*c)/(4*b)+2; do_triple(mode,0,b,c,d1,d2,Ti,To); }
  i64 amax=(i64)sqrtl(sqrtl(16.0L*X/27.0L))+1;
  for(i64 a=1;a<=amax;a++){
    long double t=sqrtl(X/3.0L)-0.75L*a*a; long double s=t>0?sqrtl(t):0;
    i64 b1=(i64)floorl(-1.5L*a-s)-2, b2=(i64)ceill(s)+2;
    long double vmax=0.25L+cbrtl(X/(4.0L*a*a*a*a));
    for(i64 b=b1;b<=b2;b++){
      i64 clo=a+(( -b-a)<0?(-b-a):0)-2;
      long double ex=0; if(-b-a>ex)ex=-b-a; if(b<=0&&b>=-2*a){ long double e2=(long double)b*b/(4.0L*a); if(e2>ex)ex=e2; }
      // tighter v bound: (4v-1)(m2+v-1/4)^2 <= X/a^4, m2 = min_u (3u/2-b/a)^2 over u in [-1,0]
      long double ba=(long double)b/a, m2=0; if(ba>0)m2=ba*ba; else if(ba<-1.5L)m2=(ba+1.5L)*(ba+1.5L);
      long double rhs=X/((long double)a*a*a*a), vlo=1.0L, vhi=vmax+1;
      if((4*vlo-1)*(m2+vlo-0.25L)*(m2+vlo-0.25L)>rhs*1.0000001L) continue;
      for(int it=0;it<50;it++){ long double vm=(vlo+vhi)/2; if((4*vm-1)*(m2+vm-0.25L)*(m2+vm-0.25L)>rhs) vhi=vm; else vlo=vm; }
      i64 chi=(i64)ceill(a*vhi*1.000001L+ex)+2;
      for(i64 c=clo;c<=chi;c++){
        i64 u2=(a+b)*(a+b)+a*c; if(u2<0) continue;
        if(mode==1 && b%3==0 && (a*c)%3!=0) continue;
        i64 d1=cdiv(b*c,a), d2=fdiv(b*c+u2,a);
        // C3: d^2 - b d + (ac - a^2) >= 0  -> outside the open root interval
        i64 dd=b*b-4*(a*c-a*a);
        if(dd<=0) do_triple(mode,a,b,c,d1,d2,Ti,To);
        else { double sd=sqrt((double)dd);
          i64 e1=(i64)floor((b-sd)/2)+1, e2=(i64)ceil((b+sd)/2)-1; // allowed: d<=e1 or d>=e2 (padded)
          if(e1>=e2-1) do_triple(mode,a,b,c,d1,d2,Ti,To);
          else { do_triple(mode,a,b,c,d1,(d2<e1?d2:e1),Ti,To); do_triple(mode,a,b,c,(d1>e2?d1:e2),d2,Ti,To); } }
      }
    }
  }
}
static int tab[256];
int main(int argc,char**argv){
  if(argc<5){fprintf(stderr,"usage: cub L H ckptfile out\n");return 1;}
  Lseg=atoll(argv[1]); Hseg=atoll(argv[2]);
  if(Lseg%4||Hseg%4){fprintf(stderr,"L,H must be multiples of 4\n");return 1;}
  i64 X[200]; int nx=0; { FILE*f=fopen(argv[3],"r"); char line[512]; while(fgets(line,512,f)){ if(line[0]<'0'||line[0]>'9')continue; X[nx++]=atoll(line);} fclose(f);}
  baseR=Lseg/2; size_t szR=(Hseg-Lseg)/2+4;
  NL=(Lseg/3)/4*4; NH=(Hseg/3/4+2)*4; baseN=NL/2; size_t szN=(NH-NL)/2+4;
  RA=calloc(szR,1); C3=calloc(szR,1); CN=calloc(szN,1);
  if(!RA||!C3||!CN){fprintf(stderr,"alloc\n");return 2;}
  enum_real(Lseg,Hseg); fprintf(stderr,"real done %llu trip %llu %llu\n",nform_real,ntrip,ntrip2);
  enum_cplx(1,3*Lseg,3*Hseg); fprintf(stderr,"c3 done %llu trip %llu %llu\n",nform_c3,ntrip,ntrip2);
  enum_cplx(2,NL,NH); fprintf(stderr,"cn done %llu slow %llu\n",nform_cn,nslow);
  for(int i=0;i<256;i++)tab[i]=-1; tab[1]=0;tab[2]=1;tab[5]=2;tab[14]=3;tab[41]=4;tab[122]=5;
  // squarefree sieve (odd prime squares) in blocks
  i64 plim=(i64)sqrtl((long double)Hseg)+2; uint8_t*comp=calloc(plim+1,1); i64*pr=malloc(sizeof(i64)*(plim/2+10)); int np=0;
  for(i64 p=3;p<=plim;p+=2){ if(!comp[p]){pr[np++]=p; for(i64 q=p*p;q<=plim;q+=2*p)comp[q]=1;} }
  const i64 BL=1<<22; uint8_t*nsf=malloc(BL);
  static unsigned long long cnt[200][5][3]; unsigned long long bad=0, viol=0, nfund=0; memset(cnt,0,sizeof cnt);
  int kb=0;
  FILE*fo=fopen(argv[4],"w");
  for(i64 s=Lseg;s<Hseg;s+=BL){
    i64 e=s+BL; if(e>Hseg)e=Hseg; memset(nsf,0,BL);
    for(int i=0;i<np;i++){ i64 p2=pr[i]*pr[i]; if(p2>=e)break; for(i64 q=cdiv(s,p2)*p2;q<e;q+=p2) nsf[q-s]=1; }
    for(i64 d=(s<2?2:s);d<e;d++){
      if(nsf[d-s]) continue; int m=d&15; if(!((d&3)==1||m==8||m==12)) continue;
      if(d>X[nx-1]) continue;
      while(d>X[kb])kb++;
      nfund++;
      int cr=RA[2*(d>>2)+(d&1)-baseR], cm;
      if(d%3) cm=C3[2*(d>>2)+(d&1)-baseR]; else { i64 n=d/3; int r=n&3; if(!(r==0||r==3)){bad++;fprintf(fo,"BADN %lld\n",(long long)d);continue;} cm=CN[2*(n>>2)+(r==3)-baseN]; }
      int r=tab[cr], rp=tab[cm];
      if(r<0||rp<0){ bad++; if(bad<1000)fprintf(fo,"BAD %lld %d %d\n",(long long)d,cr,cm); continue; }
      int ee=rp-r; if(ee<0||ee>1){ viol++; if(viol<1000)fprintf(fo,"VIOL %lld %d %d\n",(long long)d,r,rp); continue; }
      if(r>4){bad++;continue;}
      cnt[kb][r][ee]++;
      if(r>=3||rp>=4) fprintf(fo,"BIG %lld %d %d\n",(long long)d,r,rp);
    }
  }
  for(int k=0;k<nx;k++){ fprintf(fo,"BIN %d %lld",k,(long long)X[k]); for(int r=0;r<5;r++)for(int ee=0;ee<2;ee++)fprintf(fo," %llu",cnt[k][r][ee]); fprintf(fo,"\n"); }
  fprintf(fo,"STAT L %lld H %lld nfund %llu bad %llu viol %llu forms_real %llu forms_c3 %llu forms_cn %llu slow %llu\n",(long long)Lseg,(long long)Hseg,nfund,bad,viol,nform_real,nform_c3,nform_cn,nslow);
  fprintf(fo,"DONE\n"); fclose(fo); return 0;
}
